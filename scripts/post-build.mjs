// Bake dist/index.html into api/_template.js so the share function can
// inject per-result OG tags without reading the filesystem at runtime.
import fs from 'node:fs/promises'

const html = await fs.readFile('dist/index.html', 'utf8')
const body = `// Auto-generated by scripts/post-build.mjs — do not edit.
export const HTML_TEMPLATE = ${JSON.stringify(html)}
`
await fs.writeFile('api/_template.js', body)
console.log(`✓ api/_template.js  (${(body.length / 1024).toFixed(1)} KB)`)
